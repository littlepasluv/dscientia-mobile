import 'package:flutter/material.dart';

import '../../../reports/domain/entities/community_risk_report_draft.dart';
import '../../data/dtos/ai_insight_response.dart';
import '../../domain/services/mock_ai_insight_generator.dart';
import '../../../../config/theme/app_spacing.dart';
import '../../../../shared/widgets/app_hero_card.dart';
import '../../../../shared/widgets/app_page_shell.dart';
import '../../../../shared/widgets/app_section_header.dart';
import '../../../../shared/widgets/app_status_badge.dart';

class AiInsightResultScreen extends StatelessWidget {
  final CommunityRiskReportDraft report;
  final AiInsightResponse? backendInsight;

  const AiInsightResultScreen({
    required this.report,
    this.backendInsight,
    super.key,
  });

  @override
  Widget build(BuildContext context) {
    final localInsight = backendInsight == null
        ? const MockAiInsightGenerator().generate(report)
        : null;

    final priorityLabel = backendInsight != null
        ? _formatRiskLabel(backendInsight!.riskLevel)
        : localInsight!.priorityLabel;

    final summary = backendInsight?.narrativeSummary ?? localInsight!.summary;

    final priorityRationale = backendInsight != null
        ? 'Risk level: $priorityLabel. Generated by ${backendInsight!.modelProvider} using ${backendInsight!.modelName} with ${(backendInsight!.confidenceScore * 100).round()}% confidence.'
        : 'Priority level: ${localInsight!.priorityLabel}. ${localInsight.priorityRationale}';

    final suggestedAction = backendInsight != null
        ? backendInsight!.recommendedActions.first
        : localInsight!.suggestedAction;

    final actionSteps =
        backendInsight?.recommendedActions ?? localInsight!.actionSteps;

    final ethicalNote = backendInsight != null
        ? 'This backend-generated insight is a decision-support output. It should be validated by local community leaders before action is taken.'
        : localInsight!.ethicalNote;

    return AppPageShell(
      scrollable: false,
      topPadding: 0,
      bottomPadding: 0,
      appBar: AppBar(title: const Text('AI Insight Result')),
      child: SafeArea(
        child: SingleChildScrollView(
          padding: const EdgeInsets.all(AppSpacing.lg),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              AppHeroCard(
                title: 'AI-Powered Community Resilience Insight',
                description: backendInsight != null
                    ? 'Generated from the Laravel backend API using the configured AI provider contract.'
                    : 'Generated from the submitted community risk report as a local MVP preview before IBM/watsonx integration.',
                icon: Icons.auto_awesome_outlined,
                trailing: Wrap(
                  spacing: AppSpacing.xs,
                  runSpacing: AppSpacing.xs,
                  children: [
                    AppStatusBadge(
                      label: backendInsight != null
                          ? 'Backend AI Insight'
                          : 'Mock AI Insight',
                      tone: AppStatusTone.ai,
                      icon: Icons.auto_awesome_outlined,
                    ),
                    AppStatusBadge(
                      label: priorityLabel,
                      tone: AppStatusTone.info,
                      icon: Icons.priority_high_outlined,
                    ),
                  ],
                ),
              ),
              const SizedBox(height: AppSpacing.xl),
              const AppSectionHeader(
                title: 'Source Report',
                description:
                    'Review the community report context used to generate this insight.',
              ),
              _ReportContextCard(report: report),
              const SizedBox(height: AppSpacing.xl),
              const AppSectionHeader(
                title: 'AI Decision Support',
                description:
                    'Use these recommendations as decision support and validate them with local context.',
              ),
              _InsightCard(
                icon: Icons.summarize_outlined,
                title: 'AI Risk Summary',
                content: summary,
              ),
              const SizedBox(height: AppSpacing.md),
              _InsightCard(
                icon: Icons.priority_high_outlined,
                title: 'Priority Assessment',
                content: priorityRationale,
              ),
              const SizedBox(height: AppSpacing.md),
              _InsightCard(
                icon: Icons.task_alt_outlined,
                title: 'Suggested Community Action',
                content: suggestedAction,
              ),
              const SizedBox(height: AppSpacing.md),
              _ActionStepsCard(actionSteps: actionSteps),
              const SizedBox(height: AppSpacing.md),
              _InsightCard(
                icon: Icons.verified_user_outlined,
                title: 'Ethical AI Note',
                content: ethicalNote,
              ),
              const SizedBox(height: AppSpacing.xl),
              Align(
                alignment: Alignment.centerLeft,
                child: FilledButton.icon(
                  onPressed: () {
                    Navigator.of(context).pop();
                  },
                  icon: const Icon(Icons.arrow_back),
                  label: const Text('Back'),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }

  String _formatRiskLabel(String value) {
    final words = value
        .split(RegExp(r'[_\s-]+'))
        .where((word) => word.isNotEmpty)
        .map((word) => '${word[0].toUpperCase()}${word.substring(1)}')
        .join(' ');

    return words.isEmpty ? 'Unknown Risk' : '$words Risk';
  }
}

class _ReportContextCard extends StatelessWidget {
  final CommunityRiskReportDraft report;

  const _ReportContextCard({required this.report});

  @override
  Widget build(BuildContext context) {
    return _InsightCard(
      icon: Icons.assignment_outlined,
      title: 'Report Details',
      content:
          '${report.title}\n\nCategory: ${report.category}\nLocation: ${report.location}\nUrgency: ${report.urgency}\n\n${report.description}',
    );
  }
}

class _ActionStepsCard extends StatelessWidget {
  final List<String> actionSteps;

  const _ActionStepsCard({required this.actionSteps});

  @override
  Widget build(BuildContext context) {
    return Card(
      child: Padding(
        padding: const EdgeInsets.all(AppSpacing.lg),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              'Recommended Action Steps',
              style: Theme.of(
                context,
              ).textTheme.titleLarge?.copyWith(fontWeight: FontWeight.bold),
            ),
            const SizedBox(height: AppSpacing.sm),
            ...actionSteps.map(
              (step) => Padding(
                padding: const EdgeInsets.only(bottom: AppSpacing.xs),
                child: Row(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    const Icon(Icons.check_circle_outline, size: 20),
                    const SizedBox(width: AppSpacing.xs),
                    Expanded(child: Text(step)),
                  ],
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

class _InsightCard extends StatelessWidget {
  final IconData icon;
  final String title;
  final String content;

  const _InsightCard({
    required this.icon,
    required this.title,
    required this.content,
  });

  @override
  Widget build(BuildContext context) {
    final colorScheme = Theme.of(context).colorScheme;

    return Card(
      child: Padding(
        padding: const EdgeInsets.all(AppSpacing.lg),
        child: Row(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            CircleAvatar(
              backgroundColor: colorScheme.secondaryContainer,
              foregroundColor: colorScheme.onSecondaryContainer,
              child: Icon(icon),
            ),
            const SizedBox(width: AppSpacing.md),
            Expanded(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    title,
                    style: Theme.of(context).textTheme.titleLarge?.copyWith(
                      fontWeight: FontWeight.bold,
                    ),
                  ),
                  const SizedBox(height: AppSpacing.xs),
                  Text(content),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }
}
